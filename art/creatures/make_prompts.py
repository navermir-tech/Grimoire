def write():
    out = os.path.join(HERE, "prompts")
    os.makedirs(out, exist_ok=True)
    for c in CREATURES:
        cid = c[0]
        with open(os.path.join(out, cid + ".txt"), "w", encoding="utf-8", newline="\n") as f:
            f.write(concept_prompt(c))
        with open(os.path.join(out, cid + "-sheet.txt"), "w", encoding="utf-8", newline="\n") as f:
            f.write(sheet_prompt(c))
        # 4면 시트는 콘셉트 그림을 참고로 준다(같은 개체 유지).
        with open(os.path.join(out, cid + "-sheet.refs"), "w", encoding="utf-8", newline="\n") as f:
            f.write(os.path.join(HERE, "raw", cid + ".png"))
    print(f"{len(CREATURES)} 종 × 2(콘셉트 · 4면 시트) 프롬프트 → {out}", file=sys.stderr)


def role_text(role):
    # 역할 칸은 생태 역할만 — 길들인 뒤 하는 일은 기능 칸에.
    kept = [r for r in role.split(" · ") if r not in ("탈것", "일꾼", "가축", "운반", "식용")]
    return " · ".join(kept) or "주변"


def md():
    lines = []
    kinds = [k for k, _ in FUNCTION_KINDS]
    lines.append("### 기능별 생물 수\n")
    lines.append("| # | 지역 | 종 | " + " | ".join(kinds) + " | 기능 없음 | 거점 최소 기능(" + " · ".join(BASE_MINIMUM) + ") — 이 지역만 / 누적 |")
    lines.append("|---|---|---|" + "---|" * (len(kinds) + 2))
    tot = {k: 0 for k in kinds}; tot_none = 0
    seen = set()  # 1번 지역부터 차례로 열린 지역까지 쌓인 기능
    for reg, (rname, _, _) in REGIONS.items():
        rows = [c for c in CREATURES if c[1] == reg]
        cnt = {k: sum(1 for c in rows if any(f[0] == k for f in FUNCTIONS[c[0]])) for k in kinds}
        none = sum(1 for c in rows if not FUNCTIONS[c[0]])
        for k in kinds: tot[k] += cnt[k]
        tot_none += none
        missing = [k for k in BASE_MINIMUM if not cnt[k]]
        check = "✅" if not missing else "빠짐: " + " · ".join(missing)
        for k in BASE_MINIMUM:
            if cnt[k]: seen.add(k)
        check += " / " + ("✅" if all(k in seen for k in BASE_MINIMUM) else "빠짐")
        lines.append(f"| {reg} | {rname} | {len(rows)} | " + " | ".join(str(cnt[k] or "") for k in kinds) + f" | {none} | {check} |")
    multi = sum(1 for c in CREATURES if len(FUNCTIONS[c[0]]) > 1)
    lines.append(f"|  | **합** | **{len(CREATURES)}** | " + " | ".join(f"**{tot[k]}**" for k in kinds) + f" | **{tot_none}** | |")
    lines.append("")
    prod = {"목축", "손재주", "운반", "방범", "속성 작업"}
    n_prod = sum(1 for c in CREATURES if any(f[0] in prod for f in FUNCTIONS[c[0]]))
    n_ride = sum(1 for c in CREATURES if any(f[0] in ("날것", "탈것") for f in FUNCTIONS[c[0]]))
    lines.append(f"- 기능 없음 {tot_none}종 · 기능 있음 {len(CREATURES) - tot_none}종(그중 거점 생산 · 방범 {n_prod}종, 탈것 · 날것 {n_ride}종). 기능이 둘인 생물 {multi}종.")
    lines.append("")
    for reg, (rname, circle, focus) in REGIONS.items():
        rows = [c for c in CREATURES if c[1] == reg]
        lines.append(f"### {reg}. {rname} — {len(rows)}종\n")
        lines.append(f"서클 {circle} · 주 속성 {focus}\n")
        lines.append("| 이름 | 원전 | 각색 | 속성(주 · 부) | 크기 | 성격 | 역할 | 기능 | 서식 · 시간 | 길들이기 · 쓰임 | 희귀도 |")
        lines.append("|---|---|---|---|---|---|---|---|---|---|---|")
        for c in rows:
            cid, _, name, src, adapt, main, sub, size, height, temper, role, habitat, use, rarity, _ = c
            lines.append(f"| **{name}** `{cid}` | {src} | {adapt} | {main} · {sub} | {size}({height}) | {temper} | {role_text(role)} | {func_text(cid)} | {habitat} | {use} | {rarity} |")
        lines.append("")
    print("\n".join(lines))


