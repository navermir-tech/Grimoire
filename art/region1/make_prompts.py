def write():
    out = os.path.join(HERE, "prompts")
    os.makedirs(out, exist_ok=True)
    for job, group, title, body, comp, use_ref in JOBS:
        text = f"$imagegen\n1번 지역 콘셉트 아트 — {group} 「{title}」.\n- {body}\n- {comp}\n" + COMMON.replace("{job}", job)
        with open(os.path.join(out, job + ".txt"), "w", encoding="utf-8") as f:
            f.write(text)
        refs = os.path.join(out, job + ".refs")
        paths = ([COSTUME] if use_ref else []) + ([TOWER] if job in TOWER_JOBS else [])
        if paths:
            with open(refs, "w", encoding="utf-8") as f:
                f.write(",".join(paths))
        elif os.path.exists(refs):
            os.remove(refs)
    print(f"{len(JOBS)} 개 프롬프트 → {out}")


if __name__ == "__main__":
    if "--list" in sys.argv:
        print(" ".join(j[0] for j in JOBS))
    else:
        write()
